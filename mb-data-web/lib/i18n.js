// Le français est inclus d'office ; l'anglais est chargé par loadLocale().
export const TRANSLATIONS = { fr: FR }

// Charge le dictionnaire d'une langue s'il ne l'est pas encore. Rend une
// promesse résolue quand translate() peut servir cette langue.
export function loadLocale(locale) {
  if (TRANSLATIONS[locale]) return Promise.resolve()
  if (locale === 'en') return import('./i18n/en').then((m) => { TRANSLATIONS.en = m.default })
  return Promise.resolve()
}

