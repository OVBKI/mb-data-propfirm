//   2. GLOW PULSANT CONTINU — feGaussianBlur stdDeviation animé (4 ↔ 14) en 3.5s
//   3. GRADIENT ANIMÉ — linearGradient 3 stops qui cyclent (6s loop)
//   4. TILT 3D AU HOVER — CSS rotateX/rotateY pilotés par position souris
//
// Le wordmark "QUANTARA" est rendu séparément en texte dans HeroSection
// (pour bénéficier de la spring animation framer-motion).
//
// VIEWBOX :
//   Le SVG original est 1024×1024. Le Q icon vit dans la région X=370-710, Y=190-540.
